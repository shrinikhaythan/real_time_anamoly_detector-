import pandas as pd
import numpy as np
import tensorflow as tf
from tensorflow import keras
from tensorflow.keras import layers
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error
import joblib

# --- 1. Load Your Feature Datasets ---

try:
    train_df = pd.read_csv('train_features.csv')
    test_df = pd.read_csv('test_features.csv')
    print(f"Loaded training data with {train_df.shape[0]} windows.")
    print(f"Loaded test data with {test_df.shape[0]} windows.")
except FileNotFoundError:
    print("Error: 'train_features.csv' or 'test_features.csv' not found.")
    print("Please make sure you've run the feature extraction cell first.")

# --- 2. Pre-process the Data (CRITICAL STEP) ---

# Autoencoders are very sensitive to the scale of data.
# We will scale all features to have a mean of 0 and std dev of 1.

# IMPORTANT: We fit the scaler ONLY on the training data
scaler = StandardScaler()
train_data_scaled = scaler.fit_transform(train_df)

# We use the SAME scaler (with the mean/std from train) to transform the test data
test_data_scaled = scaler.transform(test_df)

print("\nData successfully scaled.")

# --- 3. Build the Autoencoder Model ---

n_features = train_data_scaled.shape[1] # Should be 18
encoding_dim = 8  # The "bottleneck" size. This is a good starting point.

model = keras.Sequential([
    # --- Encoder ---
    # Input layer (18 features)
    layers.Input(shape=(n_features,)),
    # First hidden layer
    layers.Dense(14, activation='relu'),
    # Bottleneck (8 features)
    layers.Dense(encoding_dim, activation='relu'),

    # --- Decoder ---
    # First decoding layer
    layers.Dense(14, activation='relu'),
    # Output layer (must match input shape: 18 features)
    layers.Dense(n_features, activation='linear') # Linear activation for reconstruction
])

# --- 4. Compile the Model ---
# We use 'mae' (Mean Absolute Error) as our loss function
model.compile(optimizer='adam', loss='mae')

model.summary()

# --- 5. Train the Model ---
print("\n--- Starting Model Training ---")

# We train the model to reconstruct its own input
# x = train_data, y = train_data
history = model.fit(
    train_data_scaled,
    train_data_scaled,
    epochs=100,
    batch_size=16,
    shuffle=True,
    validation_data=(test_data_scaled, test_data_scaled) # Use test data for validation
)

print("--- Model Training Complete ---")

# --- 6. Find the Anomaly Threshold ---
print("\n--- Finding Anomaly Threshold ---")

# Get the model's predictions (reconstructions) for the TEST data
reconstructions = model.predict(test_data_scaled)

# Calculate the Mean Absolute Error for EACH window in the test set
# This is our "reconstruction error" score
test_loss_mae = mean_absolute_error(test_data_scaled.T, reconstructions.T, multioutput='raw_values')

# Find the highest error from our "healthy" test set
max_error = np.max(test_loss_mae)

# Set our final threshold to be just above the max error
# (e.g., 10% buffer)
FINAL_THRESHOLD = max_error * 1.1

print(f"Max reconstruction error on healthy test data: {max_error:.4f}")
print(f"FINAL ANOMALY THRESHOLD (with 10% buffer): {FINAL_THRESHOLD:.4f}")

# --- 7. Save the Model and Scaler ---
# We need to save BOTH the model and the scaler

# Save the trained model
model.save('autoencoder_model.h5')
print("\nSuccessfully saved trained model to 'autoencoder_model.h5'")

# Save the scaler
joblib.dump(scaler, 'scaler.joblib')
print("Successfully saved data scaler to 'scaler.joblib'")

print("\n--- All Done! ---")

