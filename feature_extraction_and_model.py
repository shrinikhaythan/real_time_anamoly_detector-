# --- 1. Helper Function for FFT ---

def calculate_band_power(data, fs, freq_band):
    """
    Calculates the total power in a specific frequency band.
    """
    # Use Welch's method for a cleaner power spectrum (PSD)
    freqs, psd = welch(data, fs=fs, nperseg=len(data))

    # Find the indices of the frequencies that fall within our band
    band_indices = np.where((freqs >= freq_band[0]) & (freqs <= freq_band[1]))[0]

    if len(band_indices) == 0:
        return 0 # No power in this band

    # Sum up all the power values (PSD) within the band
    total_power = np.sum(psd[band_indices])

    return total_power

# --- 2. Feature Extraction Function ---

def process_files(file_list, output_filename):
    """
    Loads raw CSV files, extracts features from the "rest" data (first 30s),
    and saves them to a new CSV.
    """

    # --- Parameters ---
    WINDOW_SECONDS = 5.0
    FREQUENCY_HZ = 50
    SAMPLES_PER_WINDOW = int(WINDOW_SECONDS * FREQUENCY_HZ) # 250 samples
    OVERLAP_PERCENTAGE = 50
    STEP_SIZE = 10

    # Frequency band for tremor
    TREMOR_BAND = [4, 6] # 4 Hz to 6 Hz

    # --- IMPORTANT: We only process the "rest" data ---
    # 30 seconds * 50 Hz = 1500 rows
    SAMPLES_TO_PROCESS = 1500

    all_feature_vectors = []

    print(f"\n--- Processing {output_filename} ---")
    print(f"Found {len(file_list)} files.")

    for file in file_list:
        try:
            # Load the raw data
            df = pd.read_csv(file)

            # --- THIS IS THE KEY: We filter for "rest" data ---
            # We select ONLY the first 1500 rows (30 seconds)
            raw_data = df[['ax', 'ay', 'az', 'gx', 'gy', 'gz']].values[:SAMPLES_TO_PROCESS]

            # Slide a window over this 1500-row chunk of "rest" data
            for i in range(0, len(raw_data) - SAMPLES_PER_WINDOW, STEP_SIZE):
                window = raw_data[i : i + SAMPLES_PER_WINDOW]

                # --- Calculate Features for this Window ---
                std_devs = np.std(window, axis=0)
                means = np.mean(window, axis=0)

                powers_4_6hz = []
                for col_index in range(window.shape[1]): # Iterate 0 through 5
                    axis_data = window[:, col_index]
                    power = calculate_band_power(axis_data, FREQUENCY_HZ, TREMOR_BAND)
                    powers_4_6hz.append(power)

                # Combine all 18 features into one vector
                feature_vector = np.concatenate((std_devs, means, np.array(powers_4_6hz)))
                all_feature_vectors.append(feature_vector)

        except Exception as e:
            print(f"Error processing {file}: {e}")

    print(f"Feature extraction complete. Total windows created: {len(all_feature_vectors)}")

    # --- Save the Final Dataset ---
    feature_columns = [
        'ax_std', 'ay_std', 'az_std', 'gx_std', 'gy_std', 'gz_std',
        'ax_mean', 'ay_mean', 'az_mean', 'gx_mean', 'gy_mean', 'gz_mean',
        'ax_4_6hz_pwr', 'ay_4_6hz_pwr', 'az_4_6hz_pwr',
        'gx_4_6hz_pwr', 'gy_4_6hz_pwr', 'gz_4_6hz_pwr'
    ]

    features_df = pd.DataFrame(all_feature_vectors, columns=feature_columns)
    features_df.to_csv(output_filename, index=False)
    print(f"Successfully saved final features to '{output_filename}'")

